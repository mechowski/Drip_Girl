import { test, expect } from '@playwright/test'

test('сквозной производственный сценарий с сохранением и архивом', async ({ page }) => {
  const errors: string[] = []
  page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()) })
  await page.goto('/')
  await page.getByRole('button', { name: 'Администратор' }).click()
  await page.getByLabel('Пароль').fill('1337')
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await page.getByRole('link', { name: 'Админпанель' }).click()
  await page.getByRole('button', { name: 'Заполнить тестовыми данными' }).click()
  await expect(page.getByText('Демонстрационные лоты, сток и состав добавлены')).toBeVisible()
  await expect(page.locator('.setting-row')).toHaveCount(4)
  await page.getByRole('link', { name: 'Сток', exact: true }).click()
  await expect(page.locator('.inventory-row')).toHaveCount(4)
  await page.getByRole('link', { name: 'Сборка', exact: true }).click()
  await expect(page.getByText('Восточная коллекция ×16')).toBeVisible()
  await page.getByLabel('Количество Восточная коллекция ×16').fill('2')
  await page.getByRole('button', { name: 'В план' }).click()
  await page.getByRole('button', { name: 'Сформировать план' }).click()
  await page.getByRole('button', { name: 'Подтвердить резерв' }).click()
  await expect(page.getByText('Резерв подтверждён')).toBeVisible()
  await page.getByRole('button', { name: 'Отчитаться' }).click()
  await page.getByLabel('Фактически собрано наборов').fill('1')
  await page.getByRole('button', { name: 'Отправить отчёт' }).click()
  await expect(page.getByText('Выполнено частично', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Отчитаться' }).click()
  await page.getByLabel('Сборщик').selectOption({ label: 'Петрова Мария' })
  await page.getByLabel('Фактически собрано наборов').fill('1')
  await page.getByRole('button', { name: 'Отправить отчёт' }).click()
  await expect(page.getByText('Выполнено', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText('Выполнено', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Отчёты', exact: true }).click()
  await page.getByRole('button', { name: 'Завершить день' }).click()
  await page.getByRole('button', { name: 'Подтвердить завершение' }).click()
  await expect(page.getByText('День завершён, отчёт сохранён в архив')).toBeVisible()
  await expect(page.locator('aside .surface button')).toHaveCount(1)
  await page.getByRole('link', { name: 'Админпанель' }).click()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Экспорт JSON' }).click()
  const download = await downloadPromise
  const backupPath = await download.path()
  await page.locator('input[type=file]').setInputFiles(backupPath!)
  await page.getByRole('button', { name: 'Заменить данные' }).click()
  await expect(page.getByText('Резервная копия восстановлена')).toBeVisible()
  await page.getByRole('link', { name: 'Отчёты', exact: true }).click()
  await page.reload()
  await expect(page.getByRole('button', { name: 'День завершён' })).toBeDisabled()
  expect(errors).toEqual([])
})
