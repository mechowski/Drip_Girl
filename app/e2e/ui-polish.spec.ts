import { test, expect } from '@playwright/test'

test('тема переключается без ошибок и сохраняет интерфейс доступным', async ({ page }) => {
  const errors: string[] = []
  page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()) })
  await page.goto('/')
  const dark = page.getByRole('button', { name: 'Включить тёмную тему' })
  await dark.click()
  await expect(page.locator('html')).toHaveClass('dark')
  await expect(page.locator('html')).toHaveCSS('color-scheme', 'dark')
  await expect(page.getByRole('button', { name: 'Включить светлую тему' })).toBeEnabled()
  await page.reload()
  await expect(page.locator('html')).toHaveClass('dark')
  await page.getByRole('button', { name: 'Включить светлую тему' }).click()
  await expect(page.locator('html')).not.toHaveClass('dark')
  await expect(page.locator('html')).toHaveCSS('color-scheme', 'light')

  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.getByRole('button', { name: 'Режим администратора' }).click()
  await page.getByRole('button', { name: 'Новый лот' }).click()
  await expect(page.getByRole('dialog', { name: 'Новый лот' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  expect(errors).toEqual([])
})

test('новый дашборд открывается и адаптируется к мобильному экрану', async ({ page }) => {
  const errors: string[] = []
  page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()) })
  await page.goto('/today')
  await expect(page.getByRole('heading', { name: 'Сегодня' })).toBeVisible()
  await expect(page.locator('.stats-strip > div')).toHaveCount(3)
  await expect(page.getByRole('heading', { name: 'Дегазация на неделе' })).toBeVisible()
  await page.getByRole('link', { name: 'Лоты', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Лоты кофе' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Все', exact: true })).toHaveAttribute('aria-pressed', 'true')

  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto('/today')
  await expect(page.getByRole('heading', { name: 'Сегодня' })).toBeVisible()
  const dimensions = await page.evaluate(() => ({ content: document.documentElement.scrollWidth, viewport: window.innerWidth }))
  expect(dimensions.content).toBeLessThanOrEqual(dimensions.viewport)
  expect(errors).toEqual([])
})

test('показывает админские действия только после включения режима в этой вкладке', async ({ page }) => {
  await page.goto('/today')
  const toggle = page.getByRole('button', { name: 'Режим администратора' })
  const adminLink = page.getByRole('link', { name: 'Админпанель' })
  const warnings = page.getByRole('button', { name: /Предупреждения:/ })
  const decisions = page.getByRole('heading', { name: 'Требует решения' })

  await expect(toggle).toHaveAttribute('aria-pressed', 'false')
  await expect(adminLink).toHaveCount(0)
  await expect(warnings).toHaveCount(0)
  await expect(decisions).toHaveCount(0)

  await page.goto('/admin?section=journal')
  await expect(page).toHaveURL(/\/today$/)
  await page.goto('/employees')
  await expect(page).toHaveURL(/\/today$/)

  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('dialog', { name: 'Доступ администратора' })).toHaveCount(0)
  await expect(adminLink).toBeVisible()
  await expect(warnings).toBeVisible()
  await expect(decisions).toBeVisible()

  await adminLink.click()
  await expect(page.getByRole('heading', { name: 'Админпанель' })).toBeVisible()
  await expect(page.getByLabel('Пароль локального администратора')).toHaveCount(0)
  await page.reload()
  await expect(toggle).toHaveAttribute('aria-pressed', 'true')
  await toggle.click()
  await expect(page).toHaveURL(/\/today$/)
  await expect(toggle).toHaveAttribute('aria-pressed', 'false')
  await expect(adminLink).toHaveCount(0)
  await expect(warnings).toHaveCount(0)

  await page.goto('/assembly#plan-draft')
  await expect(page.getByRole('heading', { name: 'Задания участка' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'План', exact: true })).toHaveCount(0)
  await page.goto('/compositions?tab=google')
  await expect(page.getByRole('button', { name: /Все составы/ })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Google Sheets', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Получить листы' })).toHaveCount(0)
})
